#!/usr/bin/env python3
"""Download the CC0 assets listed in data/assets.json from Poly Haven into art/vendor/,
then regenerate docs/CREDITS.md. Safe to re-run: existing files are skipped.
Usage: python3 tools/fetch_assets.py [--only ID ...]"""
import json, os, sys, urllib.request, concurrent.futures as cf

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
API = "https://api.polyhaven.com"
UA = {"User-Agent": "greenfall-asset-fetch/1.0"}
MAPS = {"Diffuse": "diff", "nor_gl": "nor_gl", "arm": "arm"}


def get_json(url):
    with urllib.request.urlopen(urllib.request.Request(url, headers=UA), timeout=60) as r:
        return json.load(r)


def download(url, dest):
    if os.path.exists(dest) and os.path.getsize(dest) > 0:
        return 0
    os.makedirs(os.path.dirname(dest), exist_ok=True)
    tmp = dest + ".part"
    with urllib.request.urlopen(urllib.request.Request(url, headers=UA), timeout=120) as r, open(tmp, "wb") as f:
        f.write(r.read())
    os.replace(tmp, dest)
    return os.path.getsize(dest)


def fetch_model(aid, res):
    files = get_json(f"{API}/files/{aid}")
    g = files["gltf"].get(res) or files["gltf"][sorted(files["gltf"])[0]]
    g = g["gltf"]
    base = os.path.join(ROOT, "art/vendor/polyhaven/models", aid)
    n = download(g["url"], os.path.join(base, os.path.basename(g["url"])))
    for rel, info in g.get("include", {}).items():
        n += download(info["url"], os.path.join(base, rel))
    return n


def fetch_texture(aid, res):
    files = get_json(f"{API}/files/{aid}")
    base = os.path.join(ROOT, "art/vendor/polyhaven/textures", aid)
    n = 0
    for key, short in MAPS.items():
        if key not in files or res not in files[key]:
            continue
        entry = files[key][res].get("jpg") or files[key][res].get("png")
        if entry:
            ext = os.path.splitext(entry["url"])[1]
            n += download(entry["url"], os.path.join(base, f"{aid}_{short}_{res}{ext}"))
    return n


def info(aid):
    try:
        return get_json(f"{API}/info/{aid}")
    except Exception:
        return {}


def main():
    manifest = json.load(open(os.path.join(ROOT, "data/assets.json")))
    res = manifest.get("resolution", "1k")
    only = set(sys.argv[sys.argv.index("--only") + 1:]) if "--only" in sys.argv else None
    jobs = [("model", a) for a in manifest["polyhaven_models"]] + [("texture", a) for a in manifest["polyhaven_textures"]]
    if only:
        jobs = [j for j in jobs if j[1] in only]
    total = 0
    with cf.ThreadPoolExecutor(6) as ex:
        futs = {ex.submit(fetch_model if k == "model" else fetch_texture, a, res): (k, a) for k, a in jobs}
        for f in cf.as_completed(futs):
            k, a = futs[f]
            try:
                n = f.result()
                total += n
                print(f"ok   {k:7s} {a} ({n/1e6:.1f} MB new)")
            except Exception as e:
                print(f"FAIL {k:7s} {a}: {e}")
    print(f"downloaded {total/1e6:.1f} MB")
    # Credits
    lines = ["# Credits", "", "All third-party assets are CC0 (public domain) from Poly Haven (https://polyhaven.com).",
             "Regenerated by `tools/fetch_assets.py`. Everything else (code, procedural meshes, synthesized audio, writing) is original to Greenfall.", "",
             "| Asset | Type | Author(s) | License | Source |", "|---|---|---|---|---|"]
    with cf.ThreadPoolExecutor(8) as ex:
        infos = dict(zip([a for _, a in jobs], ex.map(info, [a for _, a in jobs])))
    for k, a in jobs:
        authors = ", ".join(infos.get(a, {}).get("authors", {}).keys()) or "Poly Haven"
        lines.append(f"| {infos.get(a, {}).get('name', a)} (`{a}`) | {k} | {authors} | CC0 | https://polyhaven.com/a/{a} |")
    lines += ["", "## Fonts", "Godot's built-in default font (Open Sans / Noto, OFL/Apache) is used for UI.", ""]
    open(os.path.join(ROOT, "docs/CREDITS.md"), "w").write("\n".join(lines) + "\n")


if __name__ == "__main__":
    main()
